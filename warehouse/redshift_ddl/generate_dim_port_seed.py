"""Generates seed_dim_port.sql directly from ingestion/config.py and
batch/emr_jobs/geofence.py, so the dim_port seed data can't silently
drift from the ports the pipeline actually tracks and the anchorage
radius actually used for geofencing.

Re-run after changing PORTS or ANCHORAGE_RADIUS_KM:
    python -m warehouse.redshift_ddl.generate_dim_port_seed
"""

from __future__ import annotations

from pathlib import Path

from batch.emr_jobs.geofence import ANCHORAGE_RADIUS_KM
from ingestion.config import PORTS

OUT_PATH = Path(__file__).parent / "seed_dim_port.sql"


def generate_sql() -> str:
    lines = [
        "-- Generated by warehouse/redshift_ddl/generate_dim_port_seed.py",
        "-- from ingestion/config.py PORTS and batch/emr_jobs/geofence.ANCHORAGE_RADIUS_KM.",
        "-- Do not hand-edit -- re-run the generator instead.",
        "INSERT INTO portpulse.dim_port (port_id, port_name, center_lat, center_lon, anchorage_radius_km) VALUES",
    ]
    value_rows = [
        f"    ('{p.port_id}', '{p.name.replace(chr(39), chr(39)*2)}', {p.center_lat}, {p.center_lon}, {ANCHORAGE_RADIUS_KM})"
        for p in PORTS
    ]
    lines.append(",\n".join(value_rows) + ";")
    return "\n".join(lines) + "\n"


def main() -> None:
    OUT_PATH.write_text(generate_sql())
    print(f"Wrote {OUT_PATH}")


if __name__ == "__main__":
    main()
